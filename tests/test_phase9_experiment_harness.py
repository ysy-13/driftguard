import json
from pathlib import Path

import pytest
import yaml
from jsonschema import Draft202012Validator

from driftguard.contracts.loader import PROJECT_ROOT
from driftguard.experiments.config import ExperimentConfig
from driftguard.experiments.runner import LLMExperimentHarness


CONFIG = PROJECT_ROOT / "configs/experiments/phase9_mock_smoke.yaml"


def test_mock_config_covers_four_categories_three_faults_all_methods_and_modes():
    config = ExperimentConfig.load(CONFIG)
    assert config.families == ("M01", "M06", "M11", "M16")
    assert set(config.modes) == {"component", "end_to_end"}
    assert {"standard", "retry_only", "reflection", "validation_guided", "driftguard_symbolic"}.issubset(config.methods)
    assert "driftguard_llm" in config.methods and "oracle_symbolic_upper_bound" in config.methods


def test_real_provider_cannot_run_without_explicit_authorization():
    with pytest.raises(PermissionError, match="allow-real-api"):
        LLMExperimentHarness(PROJECT_ROOT / "configs/experiments/phase9_real_smoke.example.yaml")


def test_dry_run_builds_manifest_without_provider_calls(tmp_path):
    summary = LLMExperimentHarness(CONFIG, tmp_path, dry_run=True).run()
    manifest = json.loads((tmp_path / "manifest.json").read_text())
    assert summary["dry_run"] and summary["records"] == 0
    assert manifest["mock_provider"] and manifest["real_llm_experiment_status"] == "NOT RUN"
    assert "api_key" not in json.dumps(manifest).lower()
    assert manifest["dirty_working_tree"] and manifest["dirty_warning"]


def test_small_component_run_and_resume_are_atomic(tmp_path):
    raw = yaml.safe_load(CONFIG.read_text())
    raw["families"], raw["methods"], raw["modes"] = ["M01"], ["standard"], ["component"]
    path = tmp_path / "config.yaml"
    path.write_text(yaml.safe_dump(raw))
    output = tmp_path / "results"
    first = LLMExperimentHarness(path, output).run("component")
    second = LLMExperimentHarness(path, output).run("component", resume=True)
    assert first["records"] == first["created_records"] == 3
    assert second["resumed_records"] == 3 and second["created_records"] == 0
    assert len(list((output / "records").glob("*.json"))) == 3


def test_parallel_component_run_keeps_records_isolated_and_complete(tmp_path):
    raw = yaml.safe_load(CONFIG.read_text())
    raw["families"], raw["methods"], raw["modes"] = ["M01"], ["standard"], ["component"]
    raw["repetitions"], raw["parallelism"], raw["rate_limit_per_second"] = 2, 2, None
    path = tmp_path / "parallel.yaml"
    path.write_text(yaml.safe_dump(raw))
    output = tmp_path / "parallel-results"
    summary = LLMExperimentHarness(path, output).run("component")
    records = [json.loads(item.read_text()) for item in (output / "records").glob("*.json")]
    assert summary["records"] == summary["created_records"] == 6
    assert len(records) == 6
    assert {record["repetition"] for record in records} == {0, 1}
    assert not list((output / "records").glob("*.tmp"))


def test_formal_mock_smoke_result_when_present():
    path = PROJECT_ROOT / "results/experiments/phase9_mock_smoke/summary.json"
    if not path.exists():
        pytest.skip("formal Phase 9 smoke is generated by the final validation command")
    summary = json.loads(path.read_text())
    assert summary["records"] == 168
    assert summary["coverage"] == {
        "families": 4, "scenarios": 12,
        "fault_classes": ["AE", "TF", "PD"], "drift_categories": ["ICD", "RSD", "WPD", "SED"],
    }
    assert summary["real_llm_experiment_status"] == "NOT RUN"
    assert summary["ground_truth_leakage_count"] == summary["api_key_leakage_count"] == 0
    assert all(summary["diagnostics"].values())


def test_formal_manifest_and_all_records_validate_and_are_redacted():
    directory = PROJECT_ROOT / "results/experiments/phase9_mock_smoke"
    manifest = json.loads((directory / "manifest.json").read_text())
    manifest_schema = json.loads((PROJECT_ROOT / "benchmark/schemas/experiment_manifest_schema_v1.json").read_text())
    record_schema = json.loads((PROJECT_ROOT / "benchmark/schemas/experiment_record_schema_v1.json").read_text())
    Draft202012Validator(manifest_schema).validate(manifest)
    records = [json.loads(path.read_text()) for path in (directory / "records").glob("*.json")]
    assert len(records) == 168
    forbidden = ("api_key", "expected_patch_ref", "source_drift_id", "runtime_contract", "variant_code", "chain_of_thought", "initial_state")
    for record in records:
        Draft202012Validator(record_schema).validate(record)
        encoded = json.dumps(record).lower()
        assert not any(f'"{term}"' in encoded for term in forbidden)


